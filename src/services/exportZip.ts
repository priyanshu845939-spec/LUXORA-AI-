import JSZip from 'jszip';
import { WebsiteProject } from '../types';

export async function exportProjectToZip(project: WebsiteProject): Promise<void> {
  try {
    const zip = new JSZip();

    // Sanitize slug
    const safeName = (project.name || 'luxora-website')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '');

    const rootFolder = zip.folder(safeName) || zip;

    // Add all project files
    for (const [filePath, content] of Object.entries(project.files)) {
      if (typeof content === 'string') {
        rootFolder.file(filePath, content);
      }
    }

    // Ensure package.json exists if not already present
    if (!project.files['package.json']) {
      const packageJson = {
        name: safeName,
        private: true,
        version: '1.0.0',
        type: 'module',
        scripts: {
          dev: 'vite',
          build: 'vite build',
          preview: 'vite preview',
        },
        dependencies: {
          react: '^19.0.0',
          'react-dom': '^19.0.0',
        },
        devDependencies: {
          '@types/react': '^19.0.0',
          '@types/react-dom': '^19.0.0',
          '@vitejs/plugin-react': '^4.2.0',
          tailwindcss: '^4.0.0',
          typescript: '^5.0.0',
          vite: '^6.0.0',
        },
      };
      rootFolder.file('package.json', JSON.stringify(packageJson, null, 2));
    }

    // Ensure README.md exists
    if (!project.files['README.md']) {
      const readme = `# ${project.name}

> Generated by **LUXORA AI** — Premium AI Website Builder

## Overview
- **Category:** ${project.category}
- **Visual Style:** ${project.style}
- **Primary Accent:** ${project.palette.accent}
- **Background:** ${project.palette.bg}

## Getting Started

Follow these commands to run your project locally:

\`\`\`bash
# 1. Install dependencies
npm install

# 2. Start local development server (http://localhost:5173)
npm run dev

# 3. Create production bundle
npm run build

# 4. Preview production build locally
npm run preview
\`\`\`

## Deployment Options
You can directly deploy this project to:
- **Vercel**: Import repository or run \`vercel\`
- **Netlify**: Drag and drop the \`dist/\` folder or connect Git
- **Cloudflare Pages**: Connect Git and set build command to \`npm run build\`

---
*Created with LUXORA AI.*
`;
      rootFolder.file('README.md', readme);
    }

    // Add .gitignore
    rootFolder.file(
      '.gitignore',
      `node_modules/
dist/
.DS_Store
*.local
.env
`
    );

    // Generate zip blob
    const content = await zip.generateAsync({
      type: 'blob',
      compression: 'DEFLATE',
      compressionOptions: { level: 6 },
    });

    // Trigger download
    const url = URL.createObjectURL(content);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${safeName}-source.zip`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  } catch (error) {
    console.error('ZIP Export Failed:', error);
    throw new Error('Could not create ZIP archive. Please verify your project files.');
  }
}
